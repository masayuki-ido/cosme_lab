/**
 * 使用感の範囲を超えていそうな表現。投稿を止めるのではなく、書き直しを促す。
 * 「効果がなかった」側も同じ理由で拾う（効果の有無を論じる時点で使用感の外）。
 */
export const CAUTION_PATTERNS = [
  { re: /(シミ|しみ|そばかす|ソバカス)(が|は)?(消え|きえ|取れ|とれ|無くな|なくな|薄くな|うすくな)/, hint: "シミが消えた・薄くなった" },
  { re: /(ニキビ|にきび|吹き出物)(が|は)?(治|なお|消え|きえ|完治)/, hint: "ニキビが治った" },
  { re: /(アトピー|湿疹|皮膚炎|肌荒れ)(が|は)?(治|なお|完治)/, hint: "肌トラブルが治った" },
  { re: /(シワ|しわ|たるみ|毛穴)(が|は)?(消え|きえ|無くな|なくな|完全に)/, hint: "シワ・毛穴が消えた" },
  { re: /(美白|漂白)(効果|され|になっ)/, hint: "美白効果があった" },
  { re: /(若返|アンチエイジング効果|細胞が|再生され)/, hint: "若返り・細胞への作用" },
  { re: /(治る|治っ|治し|効く|効いた|効果絶大|劇的)/, hint: "治る・効くという断定" },
  { re: /(医者|皮膚科医|医師)(に|が)?(勧め|すすめ|推奨)/, hint: "医師が勧めているという記述" },
  { re: /(癌|がん|アレルギーが治|アトピーが治)/, hint: "病気に対する効果" }
];

export function checkText(text) {
  const t = String(text || "").trim();
  if (t.length < TEXT_MIN) return { ok: false, kind: "short", message: `${TEXT_MIN}文字以上で書いてください。` };
  if (t.length > TEXT_MAX) return { ok: false, kind: "long", message: `${TEXT_MAX}文字以内にしてください（現在${t.length}文字）。` };
  const hit = CAUTION_PATTERNS.filter(p => p.re.test(t));
  if (hit.length) {
    return {
      ok: false, kind: "caution",
      message: `「${hit.map(h => h.hint).join("」「")}」のような、効果があったかどうかの書き方が含まれています。`
        + `使い心地・香り・テクスチャー・肌の感じかたなど、使ってみた感想の範囲で書き直してください。`
    };
  }
  return { ok: true };
}

